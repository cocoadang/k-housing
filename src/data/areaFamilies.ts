/**
 * Lookup an Area Family by its unique id
 */
export function getAreaFamilyById(familyId: string): AreaFamily | undefined {
  for (const families of Object.values(AREA_FAMILIES_REGISTRY)) {
    const found = families.find((f) => f.id === familyId);
    if (found) return found;
  }
  return undefined;
}
